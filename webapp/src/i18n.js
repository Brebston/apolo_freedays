export function detectLanguage(code) {
  const short = (code || '').slice(0, 2).toLowerCase()
  return TEXTS[short] ? short : 'uk'
}

export function makeT(lang) {
  const dict = TEXTS[lang] || TEXTS.uk
  return (key, vars = {}) => {
    const template = dict[key] ?? TEXTS.uk[key] ?? key
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`))
  }
}

export function monthName(lang, month, { inSentence = false } = {}) {
  const name = (MONTHS[lang] || MONTHS.uk)[month - 1]
  return inSentence && lang !== 'en' ? name.toLowerCase() : name
}

export function weekdays(lang) {
  return WEEKDAYS[lang] || WEEKDAYS.uk
}

/** 'YYYY-MM-DD' -> локальна дата без зсуву часових поясів */
export function parseISODate(iso) {
  const [y, m, d] = iso.slice(0, 10).split('-').map(Number)
  return new Date(y, m - 1, d)
}

export function toISODate(date) {
  const pad = (n) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`
}

export function formatDay(lang, iso) {
  return new Intl.DateTimeFormat(LOCALES[lang] || LOCALES.uk, { day: 'numeric', month: 'short' }).format(parseISODate(iso))
}

export function formatRange(lang, start, end) {
  return start === end ? formatDay(lang, start) : `${formatDay(lang, start)} – ${formatDay(lang, end)}`
}

export function formatDateList(lang, isoDates) {
  return isoDates.map((iso) => formatDay(lang, iso)).join(', ')
}
